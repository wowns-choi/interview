-- 공통 질문 섹션 (사용자가 이름·순서를 정한다)
CREATE TABLE IF NOT EXISTS question_section (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    sort_order  INT          NOT NULL DEFAULT 0
);

-- 공통 질문. section, kind 는 예전 버전의 컬럼으로 더 이상 쓰지 않는다 (기존 데이터 이관용으로만 남김)
CREATE TABLE IF NOT EXISTS question_template (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id  BIGINT REFERENCES question_section(id) ON DELETE CASCADE,
    content     TEXT         NOT NULL,
    sort_order  INT          NOT NULL DEFAULT 0,
    active_yn   CHAR(1)      NOT NULL DEFAULT 'Y',
    section     VARCHAR(30),
    kind        VARCHAR(20)
);
ALTER TABLE question_template ADD COLUMN IF NOT EXISTS section_id BIGINT REFERENCES question_section(id) ON DELETE CASCADE;
ALTER TABLE question_template ALTER COLUMN section DROP NOT NULL;
ALTER TABLE question_template ALTER COLUMN kind DROP NOT NULL;

CREATE TABLE IF NOT EXISTS position (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    jd_text     TEXT         NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 포지션 설명에 붙인 이미지(공고 캡처 등). image_text 는 AI가 이미지에서 읽어 낸 공고 내용
ALTER TABLE position ADD COLUMN IF NOT EXISTS image_text TEXT;
CREATE TABLE IF NOT EXISTS position_image (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    position_id   BIGINT       NOT NULL REFERENCES position(id) ON DELETE CASCADE,
    content_type  VARCHAR(50)  NOT NULL,
    image_data    BYTEA        NOT NULL,
    sort_order    INT          NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS eval_criterion (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    position_id           BIGINT       NOT NULL REFERENCES position(id) ON DELETE CASCADE,
    name                  VARCHAR(200) NOT NULL,
    description           TEXT,
    requirement           VARCHAR(20)  NOT NULL,
    category              VARCHAR(20)  NOT NULL,
    resume_assessable_yn  CHAR(1)      NOT NULL DEFAULT 'Y',
    source                VARCHAR(10)  NOT NULL,
    sort_order            INT          NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS candidate (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    position_id    BIGINT       NOT NULL REFERENCES position(id) ON DELETE CASCADE,
    display_name   VARCHAR(50)  NOT NULL,
    region         VARCHAR(50),
    career_level   VARCHAR(30),
    masked_text    TEXT,
    status         VARCHAR(20)  NOT NULL DEFAULT 'UPLOADED',
    error_message  TEXT,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS evidence (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id     BIGINT      NOT NULL REFERENCES candidate(id) ON DELETE CASCADE,
    criterion_id     BIGINT      NOT NULL REFERENCES eval_criterion(id) ON DELETE CASCADE,
    evidence_type    VARCHAR(10) NOT NULL,
    quote            TEXT,
    interpretation   TEXT,
    verified_yn      CHAR(1)     NOT NULL DEFAULT 'N',
    interview_point  TEXT
);

-- 면접 질문. section 에는 질문지를 만들 당시의 섹션 이름을 그대로 남긴다 (나중에 섹션을 바꿔도 결과는 유지)
CREATE TABLE IF NOT EXISTS interview_question (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id        BIGINT       NOT NULL REFERENCES candidate(id) ON DELETE CASCADE,
    section             VARCHAR(100) NOT NULL,
    origin              VARCHAR(30)  NOT NULL,
    question_type       VARCHAR(20),
    content             TEXT         NOT NULL,
    intent              TEXT,
    good_signal         TEXT,
    warning_signal      TEXT,
    follow_ups          TEXT,
    resume_answered_yn  CHAR(1)      NOT NULL DEFAULT 'N',
    template_id         BIGINT,
    criterion_id        BIGINT,
    evidence_id         BIGINT,
    priority            INT,
    sort_order          INT          NOT NULL DEFAULT 0,
    answer              TEXT
);
ALTER TABLE interview_question ADD COLUMN IF NOT EXISTS answer TEXT;
ALTER TABLE interview_question ALTER COLUMN section SET DATA TYPE VARCHAR(100);

CREATE TABLE IF NOT EXISTS ai_call_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose        VARCHAR(30)  NOT NULL,
    ref_id         BIGINT,
    model          VARCHAR(100),
    input_tokens   INT,
    output_tokens  INT,
    latency_ms     INT,
    success_yn     CHAR(1)      NOT NULL,
    error_message  TEXT,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 기본 데이터를 한 번만 넣었는지 기록 (사용자가 전부 지워도 다시 생기지 않게)
CREATE TABLE IF NOT EXISTS app_setting (
    setting_key    VARCHAR(50) PRIMARY KEY,
    setting_value  VARCHAR(200)
);
